import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

function unwrapStreamJson(rawStdout) {
  const trimmed = rawStdout.trim();
  if (!trimmed.startsWith("{")) return rawStdout;
  const lines = trimmed.split("\n");
  const chunks = [];
  let parsedAny = false;
  for (const line of lines) {
    const l = line.trim();
    if (!l.startsWith("{")) continue;
    try {
      const evt = JSON.parse(l);
      parsedAny = true;
      if (typeof evt.result === "string") {
        chunks.push(evt.result);
      } else if (evt.type === "message" && typeof evt.content === "string") {
        chunks.push(evt.content);
      }
    } catch {
      return rawStdout;
    }
  }
  return parsedAny && chunks.length > 0 ? chunks.join("") : rawStdout;
}

export class GeminiCliAdapter {
  name = "gemini";
  contextFileName = "GEMINI.md";

  async isAvailable() {
    try {
      await execFileAsync("which", ["gemini"]);
      return true;
    } catch {
      return false;
    }
  }

  async syncGovernance(projectRoot, governance) {
    await fs.writeFile(
      path.join(projectRoot, this.contextFileName),
      `<!-- AUTO-GENERATED BY GWRK. DO NOT EDIT MANUALLY. -->\n\n${governance}`,
      "utf-8",
    );
  }

  dispatch(task) {
    const args = [
      "-p",
      "Follow the instructions provided on stdin.",
      "--yolo",
      "--output-format",
      "stream-json",
    ];
    if (task.model && task.model !== "default") {
      args.push("--model", task.model);
    }
    const stdin = task.stdin
      ? `${task.stdin}\n\n${task.prompt}`
      : task.prompt;
    return {
      command: "gemini",
      args,
      stdin,
      env: { ...task.env, GEMINI_CLI: "1" },
      streamable: true,
    };
  }

  parseResult(stdout, stderr, rawExitCode) {
    let exitCode = 1;
    let errorType;
    if (rawExitCode === 0) {
      exitCode = 0;
    } else if (rawExitCode === 42) {
      exitCode = 2;
      errorType = "usage_error";
    } else if (rawExitCode === 53) {
      exitCode = 1;
      errorType = "turn_limit";
    } else if (rawExitCode === 127) {
      exitCode = 127;
      errorType = "not_found";
    } else {
      exitCode = 1;
      errorType = "gate_failure";
    }
    return {
      success: exitCode === 0,
      exitCode,
      errorType,
      stdout: unwrapStreamJson(stdout),
      stderr,
      durationS: 0,
    };
  }

  async probeQuota() {
    return { available: await this.isAvailable() };
  }
}

export default GeminiCliAdapter;
