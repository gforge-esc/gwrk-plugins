import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

export class GooseAdapter {
  name = "goose";
  contextFileName = ".goosehints";

  async isAvailable() {
    try {
      await execFileAsync("which", ["goose"]);
      return true;
    } catch {
      return false;
    }
  }

  async syncGovernance(projectRoot, governance) {
    await fs.writeFile(
      path.join(projectRoot, this.contextFileName),
      `<!-- AUTO-GENERATED BY GWRK. DO NOT EDIT MANUALLY. -->\n\n${governance}`,
      "utf-8",
    );
  }

  dispatch(task) {
    const args = ["run", "--with-builtin", "developer", "-i", "-"];
    const stdin = task.stdin
      ? `${task.stdin}\n\n${task.prompt}`
      : task.prompt;
    return {
      command: "goose",
      args,
      stdin,
      env: { ...task.env },
      streamable: true,
    };
  }

  parseResult(stdout, stderr, rawExitCode) {
    const exitCode =
      rawExitCode === 0
        ? 0
        : rawExitCode === 2
          ? 2
          : rawExitCode === 127
            ? 127
            : 1;
    return {
      success: exitCode === 0,
      exitCode,
      errorType:
        exitCode === 0
          ? undefined
          : exitCode === 127
            ? "not_found"
            : exitCode === 2
              ? "usage_error"
              : "gate_failure",
      stdout,
      stderr,
      durationS: 0,
    };
  }

  async probeQuota() {
    return { available: await this.isAvailable() };
  }
}

export default GooseAdapter;
