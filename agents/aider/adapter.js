import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

export class AiderAdapter {
  name = "aider";
  supportsModelForwarding = true;
  contextFileName = "CONVENTIONS.md";

  constructor(runCatalogCommand = execFileAsync) {
    this.runCatalogCommand = runCatalogCommand;
  }

  async isAvailable() {
    try {
      await execFileAsync("which", ["aider"]);
      return true;
    } catch {
      return false;
    }
  }

  async discoverModels({ projectRoot } = {}) {
    const catalogs = await Promise.all([
      ["openai", "openai", "gpt"],
      ["anthropic", "anthropic", "claude"],
      ["gemini", "google", "gemini"],
    ].map(async ([prefix, provider, family]) => {
      const { stdout } = await this.runCatalogCommand("aider", ["--list-models", `${prefix}/`], {
        cwd: projectRoot,
        timeout: 10_000,
        maxBuffer: 1_048_576,
      });
      const models = [];
      for (const line of stdout.split("\n")) {
        const modelId = line.match(/^\s*-\s+.+\(([^()\s]+)\)\s*$/)?.[1];
        if (!modelId?.startsWith(`${prefix}/`)) continue;
        models.push({
          backend: this.name, provider,
          family: prefix === "openai" && /^openai\/o\d/.test(modelId) ? "o-series" : family,
          modelId, supportedEfforts: [], isDefault: false, hidden: false,
        });
      }
      return models;
    }));
    return [...new Map(catalogs.flat().map((model) => [model.modelId, model])).values()];
  }

  async syncGovernance(projectRoot, governance) {
    await fs.writeFile(
      path.join(projectRoot, this.contextFileName),
      `<!-- AUTO-GENERATED BY GWRK. DO NOT EDIT MANUALLY. -->\n\n${governance}`,
      "utf-8",
    );
  }

  dispatch(task) {
    const args = [
      "--yes-always",
      "--no-auto-commits",
      "--no-pretty",
      "--read",
      this.contextFileName,
    ];
    if (task.model && task.model !== "default") {
      args.push("--model", task.model);
    }
    args.push("--message-file", "-");
    const stdin = [...new Set([task.stdin, task.prompt].filter(Boolean))].join("\n\n");
    return {
      command: "aider",
      args,
      stdin,
      env: { ...task.env },
      streamable: true,
    };
  }

  parseResult(stdout, stderr, rawExitCode) {
    const exitCode =
      rawExitCode === 0
        ? 0
        : rawExitCode === 2
          ? 2
          : rawExitCode === 127
            ? 127
            : 1;
    return {
      success: exitCode === 0,
      exitCode,
      errorType:
        exitCode === 0
          ? undefined
          : exitCode === 127
            ? "not_found"
            : exitCode === 2
              ? "usage_error"
              : "gate_failure",
      stdout,
      stderr,
      durationS: 0,
    };
  }

  async probeQuota() {
    return { available: await this.isAvailable() };
  }
}

export default AiderAdapter;
